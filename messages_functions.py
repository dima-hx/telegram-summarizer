from datetime import datetime

async def get_chat_messages(client, entity, start_time: datetime, end_time: datetime):
    """
    Retrieve messages from a specified chat entity within [start_time, end_time)

    Args:
        client: Telethon client instance
        entity: Chat entity to get messages from
        start_time: timezone-aware start of the period
        end_time: timezone-aware end of the period (exclusive)

    Returns:
        List of messages from the period, newest first
    """
    messages = []

    # iter_messages goes from newest to oldest, starting strictly before offset_date
    async for message in client.iter_messages(entity=entity, offset_date=end_time):
        if message.date is None:
            continue

        if message.date < start_time:
            break

        messages.append(message)

    return messages

async def format_history(messages, tz):
    formatted = []
    for message in reversed(messages):
        if message.text:
            posted = message.date.astimezone(tz).strftime("%Y-%m-%d")
            formatted.append(f"[опубліковано {posted}]\n{message.text}")
    return "\n[DAY_DELIMITER]\n".join(formatted)

async def format_messages(messages):
    formatted = []

    for message in messages:
        # Get author name
        if message.sender:
            if hasattr(message.sender, 'first_name'):
                author = message.sender.first_name or message.sender.username or "Unknown"
            else:
                author = message.sender.title or "Unknown"
        else:
            author = "Unknown"

        # Get message text
        text = message.text or ""

        if text == "":  # Skip messages without text
            continue

        # Format reactions if present
        reactions_str = ""
        if message.reactions:
            reaction_counts = []
            for reaction in message.reactions.results:
                count = reaction.count
                # custom emoji and paid reactions have no emoticon
                emoji = getattr(reaction.reaction, 'emoticon', None) or "★"
                reaction_counts.append(f"{emoji}:{count}")
            if reaction_counts:
                reactions_str = f" [Reactions: {', '.join(reaction_counts)}]"

        # Combine into final format
        formatted_msg = f"{author}: {text}{reactions_str}"
        formatted.append(formatted_msg)

    return "\n".join(formatted)

def plural(n: int, one: str, few: str, many: str) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many

def get_output_message(summary: str, raw_messages_count: int, formatted_messages: str) -> str:
    """
    Generate the final output message with the summary and message count

    Args:
        summary: Summary text generated by the model
        raw_messages_count: Total number of messages in the chat history
        formatted_messages: Chat history that was summarized

    Returns:
        Formatted output message
    """

    # calculate the time need to spend on reading the formatted_messages for the average reader (200 words per minute)
    words_per_minute = 200
    words_count = len(formatted_messages.split())
    reading_time = round(words_count / words_per_minute, 0)

    time_str = f", збережено ~{int(reading_time)} хв вашого часу" if reading_time > 2 else ""

    messages_word = plural(raw_messages_count, "повідомлення", "повідомлення", "повідомлень")

    output_message = f"{summary}\n\n__За цей день було {raw_messages_count} {messages_word}{time_str}__"
    return output_message
